import 'reflect-metadata';
import { spawnSync } from 'node:child_process';
import { mkdtempSync, readdirSync, readFileSync, rmSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { join, resolve } from 'node:path';
import type { NestFastifyApplication } from '@nestjs/platform-fastify';
import { addSyntheticDealMember, createSyntheticTenant, startTestDatabase, type SyntheticTenant, type TestDatabase } from '@pactlab/db/testing';
import { createLogger } from '@pactlab/observability';
import { createLocalJWKSet, exportJWK, generateKeyPair, SignJWT, type CryptoKey } from 'jose';
import { afterAll, beforeAll, describe, expect, it } from 'vitest';
import { createApp } from '../app';
import { JwtIdentityVerifier } from '../auth/identity';
import { FileSystemObjectStore } from '../documents/storage-adapters';
import { syntheticPdf } from '../documents/synthetic-files';
import { InMemoryObjectStore } from '../documents/testing';
import { SignatureMalwareScanner } from '../documents/upload-policy';

const ISSUER = 'https://pactlab-test.example/';
const AUDIENCE = 'https://api.pactlab.test';
type Body = Record<string, unknown>;
type FindingView = {
  id: string;
  title: string;
  domain: string;
  status: string;
  direction: number | null;
  pricedRisk: { low: string; high: string; currency: string } | null;
  evidence: { evidenceItemId: string | null; documentCitation: { pageNumber: number; quote: string } | null; commitSha: string | null }[];
};

/**
 * T-058 acceptance: the published fintech demo folder (generated by
 * scripts/demo-data/generate.py) loaded into a fresh fintech deal through the
 * real import and document APIs surfaces the folder's three planted findings
 * as cited drafts; accepting the priced drag reaches a valuation run.
 */
describe.each(['USD', 'EUR', 'GBP'])('fintech pack acceptance (%s)', { timeout: 60_000 }, (currency) => {
  const repo = resolve(import.meta.dirname, '../../../..');
  let out = '';
  let folder = '';
  let storeDir = '';
  let db: TestDatabase;
  let app: NestFastifyApplication;
  let a: SyntheticTenant;
  let b: SyntheticTenant;
  let key: CryptoKey;
  let dealId = '';
  const tokens: Record<string, string> = {};

  const token = (subject: string, org: string) =>
    new SignJWT({ org_id: org }).setProtectedHeader({ alg: 'RS256', kid: 'test' }).setSubject(subject).setIssuer(ISSUER).setAudience(AUDIENCE).setIssuedAt().setExpirationTime('5m').sign(key);

  async function call(method: 'GET' | 'POST' | 'PATCH', url: string, who: string, payload?: unknown, headers: Record<string, string> = {}) {
    const response = await app.inject({ method, url, headers: { authorization: `Bearer ${tokens[who] ?? ''}`, ...headers }, ...(payload !== undefined ? { payload: payload as Body } : {}) });
    return { status: response.statusCode, body: (response.body ? response.json() : null) as Body };
  }

  /** Upload a CSV as a target and import it with the suggested mapping (the user would confirm it). */
  async function importCsv(file: string, target?: string) {
    const query = new URLSearchParams({ system: 'pactlab_standard', fileName: file, ...(target ? { target } : {}) });
    const uploaded = await app.inject({
      method: 'POST',
      url: `/v1/deals/${dealId}/uploads?${query.toString()}`,
      headers: { authorization: `Bearer ${tokens['lead'] ?? ''}`, 'content-type': 'text/csv' },
      payload: readFileSync(join(folder, file)),
    });
    expect(uploaded.statusCode, uploaded.body).toBe(201);
    const upload = uploaded.json() as { id: string; suggestedMapping: Body };
    const imported = await call('POST', `/v1/deals/${dealId}/uploads/${upload.id}/import`, 'lead', { mapping: upload.suggestedMapping });
    expect(imported.status, JSON.stringify(imported.body)).toBe(200);
    expect(imported.body['syncRun']).toMatchObject({ status: 'SUCCEEDED', issuesCount: 0 });
  }

  /** A PDF built as the demo kit builds it: pages split on `---page---`, lines wrapped at 92 characters. */
  const pdfOf = (markdown: string) => {
    const wrap = (text: string) =>
      text.split('\n').flatMap((paragraph) => {
        const lines: string[] = [];
        let line = '';
        for (const word of paragraph.split(/\s+/).filter(Boolean)) {
          if (`${line} ${word}`.trim().length > 92) {
            lines.push(line);
            line = word;
          } else line = `${line} ${word}`.trim();
        }
        return [...lines, line];
      });
    return Buffer.from(syntheticPdf(markdown.split(/^---page---$/m).map((page) => wrap(page.trim()))));
  };
  const uploadDocument = (fileName: string, text: string, dataClass: string) =>
    call('POST', `/v1/deals/${dealId}/documents`, 'lead', { fileName: fileName.replace(/\.md$/, '.pdf'), contentType: 'application/pdf', contentBase64: pdfOf(text).toString('base64'), dataClass });

  beforeAll(async () => {
    out = mkdtempSync(join(tmpdir(), 'pactlab-fintech-'));
    const run = spawnSync('python3', [join(repo, 'scripts/demo-data/generate.py'), out], { encoding: 'utf8' });
    if (run.status !== 0) throw new Error(`generate.py failed: ${run.stderr}`);
    folder = join(out, 'fintech', currency);
    storeDir = mkdtempSync(join(tmpdir(), 'pactlab-fintech-uploads-'));

    db = await startTestDatabase();
    a = await createSyntheticTenant(db.owner, 'Alpha');
    b = await createSyntheticTenant(db.owner, 'Bravo');
    const pair = await generateKeyPair('RS256');
    key = pair.privateKey;
    const jwk = { ...(await exportJWK(pair.publicKey)), kid: 'test', alg: 'RS256' };
    app = await createApp({
      prisma: db.prisma,
      identityVerifier: new JwtIdentityVerifier({ issuer: ISSUER, audience: AUDIENCE, keys: createLocalJWKSet({ keys: [jwk] }) }),
      logger: createLogger('api-test', { level: process.env['TEST_LOG'] ? 'error' : 'silent' }),
      uploads: { objectStore: new FileSystemObjectStore(storeDir), malwareScanner: new SignatureMalwareScanner() },
      documents: { objectStore: new InMemoryObjectStore(), malwareScanner: new SignatureMalwareScanner() },
    });
    tokens['lead'] = await token(a.subject, a.auth0OrganizationId);
    tokens['other'] = await token(b.subject, b.auth0OrganizationId);

    const pact = await call('POST', '/v1/pacts', 'lead', {
      name: 'Project Tally',
      baseCurrency: currency,
      buyer: { name: 'Alpha Capital', ownership: 'PRIVATE' },
      seller: { name: 'Tallyport Payments (synthetic)', ownership: 'PRIVATE', companyType: 'FINTECH' },
    });
    expect(pact.status, JSON.stringify(pact.body)).toBe(201);
    dealId = pact.body['id'] as string;
    // The pact's lead is the deal lead; a reviewer and a target contributor join the new deal.
    for (const role of ['REVIEWER', 'TARGET_CONTRIBUTOR'] as const) {
      const member = await addSyntheticDealMember(db.owner, { ...a, dealId }, role);
      tokens[role.toLowerCase()] = await token(member.subject, a.auth0OrganizationId);
    }

    await importCsv('invoice-lines.csv');
    await importCsv('loan-tape.csv', 'FINTECH_LOAN_TAPE');
    await importCsv('aml-alerts.csv', 'FINTECH_AML_ALERT');
    const classes: Record<string, string> = { '01-balance-sheet-2026-09-30.md': 'FINANCIAL', '99-data-room-extracts.md': 'FINANCIAL' };
    for (const file of readdirSync(join(folder, 'documents')).filter((name) => name.endsWith('.md'))) {
      const uploaded = await uploadDocument(file, readFileSync(join(folder, 'documents', file), 'utf8'), classes[file] ?? 'BUSINESS');
      expect(uploaded.status, JSON.stringify(uploaded.body)).toBe(201);
    }
    // An HR file with a look-alike clause must never be read by a rule (rule 7).
    expect((await uploadDocument('hr-notes.md', 'The Bank may terminate this program on a change of control of the employer.', 'HR')).status).toBe(201);
  }, 120_000);

  afterAll(async () => {
    await app?.close();
    await db?.stop();
    for (const dir of [out, storeDir]) if (dir) rmSync(dir, { recursive: true, force: true });
  });

  const findings = async () => ((await call('GET', `/v1/deals/${dealId}/findings`, 'lead')).body['items'] as FindingView[]).filter((finding) => finding.domain !== 'SECURITY');

  it('the three planted findings surface as cited drafts; a re-run adds nothing', async () => {
    const run = await call('POST', `/v1/deals/${dealId}/findings/pack-rules/run`, 'lead');
    expect(run.status, JSON.stringify(run.body)).toBe(200);
    expect(run.body).toMatchObject({ pack: 'FINTECH', created: 3, existing: 0, unresolvedQuotes: 0 });
    expect((await call('POST', `/v1/deals/${dealId}/findings/pack-rules/run`, 'lead')).body).toMatchObject({ created: 0, existing: 3 });

    const byTitle = Object.fromEntries((await findings()).map((finding) => [finding.title, finding]));
    const credit = byTitle['Allowance below observed loss experience'];
    expect(credit).toMatchObject({ domain: 'FINANCIAL', status: 'DRAFT', direction: -1 });
    expect(credit?.pricedRisk?.currency).toBe(currency);
    expect(credit?.evidence.some((link) => link.evidenceItemId && link.commitSha === null)).toBe(true);
    // The README's figure for this folder (e.g. USD 15,567), quoted from the balance sheet.
    const allowance = readFileSync(join(folder, 'README.md'), 'utf8').match(/allowance \(([A-Z]{3} [0-9,]+)\)/)?.[1];
    expect(credit?.evidence.find((link) => link.documentCitation)?.documentCitation?.quote).toBe(`Allowance for credit losses: ${allowance}`);

    const aml = byTitle['Alerts closed without review evidence'];
    expect(aml).toMatchObject({ domain: 'REGULATORY', direction: -1, pricedRisk: null });
    const unreviewed = Number(readFileSync(join(folder, 'README.md'), 'utf8').match(/(\d+) of 80 closed alerts/)?.[1]);
    expect(aml?.evidence.filter((link) => link.evidenceItemId)).toHaveLength(Math.min(unreviewed, 40));
    expect(aml?.title).toBe('Alerts closed without review evidence');

    const bank = byTitle['Partner bank can terminate on change of control'];
    expect(bank).toMatchObject({ domain: 'LEGAL', direction: 0 });
    expect(bank?.evidence).toHaveLength(1);
    expect(bank?.evidence[0]?.documentCitation?.pageNumber).toBe(2);
    expect(bank?.evidence[0]?.documentCitation?.quote).toMatch(/^22\.3 The Bank may terminate/);
    // The HR look-alike was never read.
    expect(Object.keys(byTitle).filter((title) => title.startsWith('Partner bank'))).toHaveLength(1);
  });

  it('accepting the priced drag reaches a valuation run as an adjustment', async () => {
    const credit = (await findings()).find((finding) => finding.title === 'Allowance below observed loss experience');
    const id = credit?.id ?? '';
    expect((await call('POST', `/v1/deals/${dealId}/findings/${id}/reviews`, 'lead', { expectedVersion: 1, decision: 'SUBMITTED', rationale: 'Loss rate checked against the tape' })).status).toBe(201);
    const accepted = await call('POST', `/v1/deals/${dealId}/findings/${id}/reviews`, 'reviewer', { expectedVersion: 2, decision: 'ACCEPTED', rationale: 'Allowance is short of observed losses' });
    expect(accepted.status, JSON.stringify(accepted.body)).toBe(201);

    const scenarios = `/v1/deals/${dealId}/valuation/scenarios`;
    const created = await call('POST', scenarios, 'lead', {
      name: 'Base case',
      values: {
        assumptions: { method: 'ARR_MULTIPLE', arr: '1000000.00', multiple: '5' },
        bridge: { cash: '0', debt: '0', debtLikeItems: '0', workingCapitalAdjustment: '0' },
        findingLinks: [{ findingId: id, point: 'HIGH' }],
      },
    });
    expect(created.status, JSON.stringify(created.body)).toBe(201);
    const scenarioId = (created.body['scenario'] as { id: string }).id;
    const ran = await call('POST', `${scenarios}/${scenarioId}/runs`, 'lead', { expectedVersion: 1 });
    expect(ran.status, JSON.stringify(ran.body)).toBe(201);
    const lines = (ran.body['latestRun'] as { result: { bridge: { lines: { kind: string; findingId?: string; amount: { amount: string } }[] } } }).result.bridge.lines;
    const line = lines.find((entry) => entry.kind === 'FINDING_ADJUSTMENT');
    expect(line?.findingId).toBe(id);
    // Decimal strings: the finding keeps a minimal decimal (52611.2), the bridge two places (52611.20).
    const [whole = '0', fraction = ''] = (credit?.pricedRisk?.high ?? '').split('.');
    expect(line?.amount.amount).toBe(`-${whole}.${fraction.padEnd(2, '0')}`);
  });

  it('is refused to a target contributor and invisible to another tenant', async () => {
    expect([403, 404]).toContain((await call('POST', `/v1/deals/${dealId}/findings/pack-rules/run`, 'target_contributor')).status);
    expect((await call('POST', `/v1/deals/${dealId}/findings/pack-rules/run`, 'other')).status).toBe(404);
  });
});
