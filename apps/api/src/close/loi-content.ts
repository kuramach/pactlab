import { z } from 'zod';
import { TERM_TITLES } from './term-sheet';

/**
 * The letter of intent's content (T-119): one maintained template whose blanks are named
 * fields, filled with values the pact records — agreed terms quoted verbatim, the parties —
 * and the fields the drafting side sets. No free-form drafting of legal prose, and nothing
 * buyer-confidential: it reads only the agreed terms, the parties and these fields.
 */
export const loiFieldsSchema = z.strictObject({
  exclusivityDays: z.number().int().min(1).max(365),
  /** Blank until the drafting side fills it; required before sending. */
  governingLaw: z.string().trim().max(200),
  expenses: z.string().trim().min(3).max(500),
  diligenceDays: z.number().int().min(1).max(365),
  targetSigningDate: z.iso.date().nullable(),
  responseDays: z.number().int().min(1).max(60),
  conditions: z.array(z.string().trim().min(3).max(300)).min(1).max(12),
});
export type LoiFields = z.infer<typeof loiFieldsSchema>;

export const DEFAULT_LOI_FIELDS: LoiFields = {
  exclusivityDays: 45,
  governingLaw: '',
  expenses: 'Each party bears its own costs and expenses, including those of its advisers.',
  diligenceDays: 30,
  targetSigningDate: null,
  responseDays: 10,
  conditions: ['Confirmatory diligence satisfactory to the buyer', 'A definitive agreement signed by both parties', 'Any approvals the transaction requires'],
};

export interface LoiInput {
  readonly dealName: string;
  readonly buyerName: string;
  readonly sellerName: string;
  readonly termsVersion: number;
  readonly agreedAt: string;
  readonly terms: readonly { readonly lever: string; readonly amount: string; readonly currency: string; readonly note: string; readonly dueOn?: string | null }[];
  readonly fields: LoiFields;
}

export interface LoiSection {
  readonly heading: string;
  readonly lines: readonly string[];
}

export interface LoiContent {
  readonly title: string;
  readonly parties: string;
  readonly nonBinding: readonly LoiSection[];
  readonly binding: readonly LoiSection[];
  readonly signatureNote: string;
  readonly notice: string;
  /** Fields still blank: the letter cannot be sent until they are filled. */
  readonly unfilled: readonly string[];
}

export const LOI_NOTICE = 'Generated by Pactlab from the agreed terms. Not legal advice; have your counsel review before signing.';

/** "1350000.00" → "USD 1,350,000.00": grouping on the decimal string, never floating point. */
export function loiMoney(amount: string, currency: string): string {
  const [whole = '0', fraction = '00'] = amount.split('.');
  return `${currency} ${whole.replace(/\B(?=(\d{3})+(?!\d))/g, ',')}.${fraction.padEnd(2, '0').slice(0, 2)}`;
}

const blank = (value: string) => (value.trim() === '' ? '[to be filled]' : value.trim());

export function loiContent(input: LoiInput): LoiContent {
  const { fields } = input;
  const price = input.terms.find((term) => term.lever === 'PURCHASE_PRICE');
  const others = input.terms.filter((term) => term.lever !== 'PURCHASE_PRICE');
  return {
    title: 'Letter of intent',
    parties: `${input.buyerName} (the buyer) and ${input.sellerName} (the seller), regarding ${input.dealName}`,
    nonBinding: [
      {
        heading: 'Price and consideration',
        lines: price
          ? [`${TERM_TITLES[price.lever] ?? price.lever}: ${loiMoney(price.amount, price.currency)}, as agreed in terms version ${input.termsVersion} on ${input.agreedAt.slice(0, 10)}.`]
          : [`As agreed in terms version ${input.termsVersion} on ${input.agreedAt.slice(0, 10)}.`],
      },
      {
        heading: 'Structure and other terms',
        lines: others.length > 0 ? others.map((term) => `${TERM_TITLES[term.lever] ?? term.lever}: ${loiMoney(term.amount, term.currency)}${term.dueOn ? `, financing in place by ${term.dueOn}` : ''}${term.note ? ` (${term.note})` : ''}`) : ['No other terms were agreed.'],
      },
      { heading: 'Diligence', lines: [`The buyer expects to complete confirmatory diligence within ${fields.diligenceDays} days of countersignature.`] },
      { heading: 'Timeline', lines: [fields.targetSigningDate ? `The parties aim to sign a definitive agreement by ${fields.targetSigningDate}.` : 'The parties will agree a timetable for the definitive agreement.'] },
      { heading: 'Conditions to closing', lines: fields.conditions },
      { heading: 'No obligation to close', lines: ['The provisions above are statements of present intent only. They create no obligation on either party to agree, sign or complete any transaction.'] },
    ],
    binding: [
      { heading: 'Exclusivity', lines: [`For ${fields.exclusivityDays} days from countersignature, the seller will not solicit, encourage or negotiate any other proposal to sell the business or its material assets.`] },
      { heading: 'Confidentiality', lines: ['Each party keeps this letter and everything exchanged under it confidential, under any confidentiality agreement already between them, or otherwise on these terms.'] },
      { heading: 'Governing law', lines: [`This letter is governed by the laws of ${blank(fields.governingLaw)}.`] },
      { heading: 'Expenses', lines: [fields.expenses] },
      { heading: 'Counterparts and electronic signature', lines: ['This letter may be signed in counterparts and by electronic signature, each of which is an original.'] },
      { heading: 'Termination', lines: ['The binding provisions end when the exclusivity period ends or a definitive agreement is signed, whichever comes first; confidentiality survives.'] },
    ],
    signatureNote: 'By signing, each party agrees to be bound only by the provisions under "Binding provisions". The provisions under "Non-binding provisions" create no legal obligation.',
    notice: LOI_NOTICE,
    unfilled: fields.governingLaw.trim() === '' ? ['governingLaw'] : [],
  };
}
